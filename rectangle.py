
def area(a, b):
    '''
    Возвращает площадь прямоугольника с заданными сторонами.
 
        Параметры:
                a (float): первая сторона - вещественное число
                b (float): вторая сторона - вещественное число

        Возвращаемое значение:
                area (float): площадь прямоугольника со сторонами a и b
    '''
    return a * b

def perimeter(a, b):
    '''
    Возвращает периметр прямоугольника с заданными сторонами.
 
        Параметры:
                a (float): первая сторона - вещественное число
                b (float): вторая сторона - вещественное число

        Возвращаемое значение:
                perimeter (float): периметр прямоугольника со сторонами a и b
    '''
    return (a + b) * 2
