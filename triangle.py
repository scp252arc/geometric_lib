
def area(a, h):
    '''
    Возвращает площадь треугольника с заданной стороной и высотой.
 
        Параметры:
                a (float): основание - вещественное число
                h (float): высота - вещественное число

        Возвращаемое значение:
                area (float): площадь квадрата по основанию a и высоте h
    '''
    return a * h / 2

def perimeter(a, b, c):
    '''
    Возвращает периметр треугольника с заданными сторонами.
 
        Параметры:
                a (float): первая сторона - вещественное число
                b (float): вторая сторона - вещественное число
                c (float): вторая сторона - вещественное число

        Возвращаемое значение:
                perimeter (float): периметр треугольника со сторонами a, b и c
    '''
    return a + b + c
